"""Pack authored 0.46 sources, preserving alpha and nearest-neighbour pixel detail."""
import json, math
from pathlib import Path
from PIL import Image
from battle_motion_art import cell, silhouette, fit, _ROWS
ROOT=Path('art/refined046')
PIECES=['cauldron','blade','socket','wall','tablet','tablet_lit','beam','chain','weight','plate','water','splash','steam','dust','handle','ledge']
POSES=['idle','left','jump','crouch','push_right','push_left','back','right','land','hit','breathe','rise']

def emit(check=False):
    outputs={};bounds=[]
    _ROWS.clear()
    src=Image.open(ROOT/'obstacles.png').convert('RGBA')
    atlas=Image.new('RGBA',(1024,1024))
    for i in range(16):
        frame=fit(cell(src,i,4,4),(256,256),6)
        b=frame.getchannel('A').point(lambda a:255 if a>96 else 0).getbbox()
        assert b and b[0]>0 and b[2]<256
        bounds.append(list(b));atlas.alpha_composite(frame,(i%4*256,i//4*256))
    outputs[Path('app/src/main/res/drawable-nodpi/obstacle_parts_046.png')]=atlas
    _ROWS.clear()
    src=Image.open(ROOT/'hero.png').convert('RGBA');atlas=Image.new('RGBA',(768,576))
    heights=[176,167,150,98,160,160,176,167,130,170,176,140]
    for i,height in enumerate(heights):
        raw=silhouette(cell(src,i,4,3)); scale=min(height/raw.height,180/raw.width)
        raw=raw.resize((round(raw.width*scale),round(raw.height*scale)),Image.Resampling.NEAREST)
        frame=Image.new('RGBA',(192,192));frame.alpha_composite(raw,((192-raw.width)//2,188-raw.height))
        atlas.alpha_composite(frame,(i%4*192,i//4*192))
    outputs[Path('app/src/main/res/drawable-nodpi/obstacle_hero_046.png')]=atlas
    # Aligned shoulder->elbow, elbow->wrist, fist. Fixed-size source caps keep pivots stable.
    _ROWS.clear()
    src=Image.open(ROOT/'arms.png').convert('RGBA');atlas=Image.new('RGBA',(192,96));limb_bounds=[]
    for i in range(6):
        raw=silhouette(cell(src,i,3,2)); size=(32,32) if i%3==2 else (32,64)
        raw=raw.resize(size,Image.Resampling.NEAREST);atlas.alpha_composite(raw,(i*32,0));limb_bounds.append([i*32,0,*size])
    outputs[Path('app/src/main/res/drawable-nodpi/combat_arms_046.png')]=atlas
    text='package com.powerfulhimchan.mapexit\n\n/** Generated by tools/obstacle_art.py from approved 0.46 source images. */\ninternal object ObstacleAtlas {\n'
    text+='    val pieces = listOf('+','.join(json.dumps(x) for x in PIECES)+')\n'
    text+='    val poses = listOf('+','.join(json.dumps(x) for x in POSES)+')\n'
    text+='    val bounds = listOf('+','.join('intArrayOf('+','.join(map(str,b))+')' for b in bounds)+')\n}\n'
    outputs[Path('app/src/main/java/com/powerfulhimchan/mapexit/ObstacleAtlas.kt')]=text.encode()
    for p,data in outputs.items():
        if check:
            assert p.exists(),str(p)
            if isinstance(data,Image.Image):
                existing=Image.open(p).convert('RGBA');assert existing.size==data.size and existing.tobytes()==data.tobytes(),str(p)
            else:assert p.read_bytes()==data,str(p)
        else:
            p.parent.mkdir(parents=True,exist_ok=True)
            if isinstance(data,Image.Image):data.save(p,optimize=True)
            else:p.write_bytes(data)
    print('Refined obstacles: 16 pieces, 12 full hero poses, 6 aligned arm segments')
