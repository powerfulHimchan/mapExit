"""Crop and pack authored feedback, shrine and selected staircase icon artwork.

No font rasterization: each numeral and label comes from its authored PNG.
Dungeon traps reuse the very same parts as their encounter scenes.
"""
import json
from pathlib import Path
from PIL import Image, ImageEnhance

ROOT = Path('art/refined052')
RES = Path('app/src/main/res/drawable-nodpi')
WORDS = ['치명타!', '방어', '완전 방어', '회피', '빗나감', '행운',
         '방패 파괴', '빈틈 공격', '공격 경감', '연속 공격', '빈틈 발생', '반격']

def trim(im):
    # Ignore almost invisible antialias fringes when calculating sprite geometry.
    b = im.getchannel('A').point(lambda a: 255 if a > 96 else 0).getbbox()
    assert b, 'Empty authored glyph'
    return im.crop(b)

def fit(im, w, h):
    scale = min(w / im.width, h / im.height)
    return im.resize((max(1, round(im.width * scale)), max(1, round(im.height * scale))), Image.Resampling.NEAREST)

def emit(check=False):
    outputs = {}; digits = []; words = []; props = []
    src = Image.open(ROOT / 'digits.png').convert('RGBA')
    atlas = Image.new('RGBA', (72 * 11, 76 * 3))
    cuts = [25, 225, 405, 590, 780, 960, 1145, 1330, 1515, 1690, 1865, 1970]
    for row in range(3):
        for col in range(11):
            glyph = trim(src.crop((cuts[col], row * 252, cuts[col + 1], (row + 1) * 252)))
            glyph = fit(glyph, 66, 68)
            x, y = col * 72 + 3, row * 76 + 4
            atlas.alpha_composite(glyph, (x, y))
            digits.append([x, y, glyph.width, glyph.height])
    outputs[RES / 'battle_digits_052.png'] = atlas
    src = Image.open(ROOT / 'words.png').convert('RGBA')
    atlas = Image.new('RGBA', (256 * 3, 80 * 4))
    for i in range(12):
        col, row = i % 3, i // 3
        glyph = trim(src.crop((col * 512, row * 256, (col + 1) * 512, (row + 1) * 256)))
        glyph = fit(glyph, 248, 68)
        x, y = col * 256 + 4, row * 80 + 6
        atlas.alpha_composite(glyph, (x, y))
        words.append([x, y, glyph.width, glyph.height])
    outputs[RES / 'battle_words_052.png'] = atlas
    # Use the production encounter sprites, not a second interpretation of a trap.
    source = Image.open(RES / 'obstacle_parts_046.png').convert('RGBA')
    pieces = ['cauldron', 'blade', 'socket', 'wall', 'tablet', 'tablet_lit', 'beam', 'chain',
              'weight', 'plate', 'water', 'splash', 'steam', 'dust', 'handle', 'ledge']
    def part(name):
        i = pieces.index(name)
        return trim(source.crop((i % 4 * 256, i // 4 * 256, i % 4 * 256 + 256, i // 4 * 256 + 256)))
    atlas = Image.new('RGBA', (256 * 7, 256))
    for i in range(7):
        frame = Image.new('RGBA', (256, 256))
        def place(name, x, y, w, h, mirror=False):
            image = fit(part(name), w, h)
            if mirror: image = image.transpose(Image.Transpose.FLIP_LEFT_RIGHT)
            frame.alpha_composite(image, (round(x + (w - image.width) / 2), round(y + h - image.height)))
        if i == 0:
            place('chain', 55, 6, 18, 103); place('chain', 182, 6, 18, 103)
            place('cauldron', 20, 72, 216, 151); place('water', 111, 208, 30, 42)
        elif i == 1:
            place('socket', 8, 203, 240, 43)
            for x, h in [(28, 105), (94, 156), (163, 120)]: place('blade', x, 238 - h, 65, h)
        elif i == 2:
            place('wall', 18, 12, 94, 231); place('wall', 144, 12, 94, 231, mirror=True)
        elif i == 3:
            place('tablet', 8, 170, 112, 76); place('tablet_lit', 122, 120, 124, 92)
        elif i == 4:
            place('chain', 44, 0, 17, 152); place('chain', 198, 0, 17, 152)
            place('beam', 8, 120, 240, 100)
        else:
            shrine = trim(Image.open(ROOT / 'heal.png').convert('RGBA'))
            shrine = fit(shrine, 244, 244)
            if i == 6:
                shrine = ImageEnhance.Color(shrine).enhance(.12)
                shrine = ImageEnhance.Brightness(shrine).enhance(.55)
            frame.alpha_composite(shrine, ((256 - shrine.width) // 2, 250 - shrine.height))
        b = frame.getchannel('A').point(lambda a: 255 if a > 96 else 0).getbbox()
        assert b
        props.append([i * 256 + b[0], b[1], b[2] - b[0], b[3] - b[1]])
        atlas.alpha_composite(frame, (i * 256, 0))
    outputs[RES / 'exploration_props_052.png'] = atlas
    outputs[RES / 'launcher_stairs_052.png'] = Image.open(ROOT / 'launcher.png').convert('RGBA').resize((512, 512), Image.Resampling.LANCZOS)
    text = 'package com.powerfulhimchan.mapexit\n\n/** Generated by tools/feedback_art_052.py; x, y, width, height. */\ninternal object FeedbackAtlas052 {\n'
    text += '    val words = listOf(' + ','.join(json.dumps(x, ensure_ascii=False) for x in WORDS) + ')\n'
    for name, bounds in [('digits', digits), ('labels', words), ('props', props)]:
        text += '    val ' + name + ' = listOf(' + ','.join('intArrayOf(' + ','.join(map(str, b)) + ')' for b in bounds) + ')\n'
    text += '}\n'
    outputs[Path('app/src/main/java/com/powerfulhimchan/mapexit/FeedbackAtlas052.kt')] = text.encode()
    for p, data in outputs.items():
        if check:
            assert p.exists(), str(p)
            if isinstance(data, Image.Image):
                old = Image.open(p).convert('RGBA')
                assert old.size == data.size and old.tobytes() == data.tobytes(), str(p)
            else: assert p.read_bytes() == data, str(p)
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            if isinstance(data, Image.Image): data.save(p, optimize=True)
            else: p.write_bytes(data)
    print('Feedback 052: 33 numeral glyphs, 12 word sprites, 7 exploration props and selected icon')

if __name__ == '__main__':
    import sys
    emit('--check' in sys.argv)
