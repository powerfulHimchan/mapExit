"""Authored silhouettes for the item expansion; uses the existing pixel palette."""
def add_item_art(sprites, Art):
    # Every armor variant has its own outline, material and construction details.
    for kind, names in {
        'shield':['buckler','tower','spiked'], 'head':['leathercap','headband','heavyhelm'],
        'body':['leatherarmor','chainmail','platearmor'], 'pants':['leatherpants','scoutpants','platepants'],
        'boots':['leatherboots','ironboots','windboots'],
    }.items():
        for index,name in enumerate(names):
            a=Art(32,40); dark,mid,light=[(12,13,14),(37,38,39),(3,4,5)][index]
            if kind=='shield':
                if index==0:
                    a.poly([(16,7),(24,10),(27,18),(24,27),(16,32),(8,27),(5,18),(8,10)],1)
                    a.poly([(16,9),(23,12),(25,18),(22,25),(16,29),(10,25),(7,18),(10,12)],14)
                    for x in [11,16,21]:a.line(x,12,x,26,12)
                    a.rect(12,15,8,8,3);a.rect(14,16,4,5,5)
                elif index==1:
                    a.poly([(5,3),(27,3),(28,23),(24,32),(16,38),(8,32),(4,23)],1)
                    a.poly([(7,5),(25,5),(26,23),(22,30),(16,35),(10,30),(6,23)],3)
                    a.rect(9,7,14,16,4);a.line(16,5,16,33,5);a.line(7,17,25,17,5)
                    a.poly([(16,13),(21,19),(16,27),(11,19)],23)
                else:
                    a.poly([(6,9),(16,5),(26,9),(25,26),(16,34),(7,26)],1)
                    a.poly([(8,10),(16,7),(24,10),(23,25),(16,31),(9,25)],4)
                    a.poly([(5,17),(0,13),(5,24)],5);a.poly([(27,17),(31,13),(27,24)],5)
                    a.poly([(16,13),(21,22),(16,29),(11,22)],3);a.poly([(16,10),(18,22),(16,26),(14,22)],6)
            elif kind=='head':
                if index==0:
                    a.poly([(7,17),(9,9),(16,6),(23,9),(25,17),(27,23),(23,27),(9,27),(5,23)],1)
                    a.poly([(8,18),(11,11),(16,8),(21,11),(24,18),(23,24),(9,24)],14)
                    a.rect(8,18,16,4,12);a.line(16,9,16,17,17);a.rect(24,21,4,3,13)
                elif index==1:
                    a.poly([(3,12),(26,10),(28,17),(5,20)],1);a.poly([(4,13),(25,11),(26,16),(5,18)],34)
                    a.rect(14,12,6,5,23);a.rect(16,13,2,3,25)
                    a.poly([(25,16),(31,21),(27,29),(25,24)],35);a.poly([(25,16),(27,24),(22,31),(22,22)],34)
                else:
                    a.poly([(5,12),(10,5),(22,5),(27,12),(27,28),(21,32),(11,32),(5,28)],1)
                    a.poly([(7,13),(11,7),(21,7),(25,13),(25,27),(20,30),(12,30),(7,27)],4)
                    a.rect(7,16,18,5,1);a.rect(10,17,5,1,35);a.rect(18,17,5,1,35)
                    a.rect(15,7,3,23,5);a.line(9,24,12,28,3);a.line(23,24,20,28,3)
            elif kind=='body':
                a.poly([(7,7),(12,5),(20,5),(25,7),(30,14),(26,20),(23,17),(24,34),(8,34),(9,17),(6,20),(2,14)],1)
                a.poly([(8,9),(12,7),(16,11),(20,7),(24,9),(27,14),(25,17),(21,14),(22,32),(10,32),(11,14),(7,17),(5,14)],mid)
                a.line(16,12,16,30,dark);a.line(11,8,9,16,light);a.line(21,8,23,16,light)
                if index==0:
                    a.line(11,11,21,26,12);a.rect(9,27,14,4,12);a.rect(15,28,4,2,23)
                elif index==1:
                    for y in range(12,30,3):
                        for x in range(11,22,3):a.rect(x,y,1,1,5)
                    a.rect(9,28,14,3,12)
                else:
                    a.poly([(11,13),(16,16),(21,13),(20,25),(16,28),(12,25)],3)
                    a.line(12,14,15,24,5);a.rect(4,11,7,5,5);a.rect(22,11,7,5,5)
                    a.rect(10,29,12,3,23)
            elif kind=='pants':
                a.poly([(7,6),(25,6),(24,20),(26,34),(17,35),(16,22),(15,35),(6,34),(8,20)],1)
                a.poly([(9,8),(23,8),(22,20),(24,32),(19,33),(17,19),(15,19),(13,33),(8,32),(10,20)],mid)
                a.rect(8,8,16,3,12);a.rect(14,8,5,3,23)
                a.line(11,13,10,30,light);a.line(21,13,22,30,light)
                if index==0:a.rect(9,16,4,5,12);a.rect(19,16,4,5,12)
                elif index==1:
                    a.rect(8,13,6,7,26);a.rect(19,23,6,5,12);a.line(19,24,23,26,23)
                else:
                    a.rect(8,19,6,6,3);a.rect(19,19,6,6,3);a.rect(8,20,6,2,5);a.rect(19,20,6,2,5)
            else:
                height=10 if index==0 else 5 if index==1 else 15
                for x in [3,18]:
                    a.poly([(x+2,height),(x+9,height),(x+9,25),(x+12,28),(x+12,33),(x,33),(x,27),(x+2,24)],1)
                    a.poly([(x+3,height+2),(x+8,height+2),(x+8,26),(x+10,29),(x+10,31),(x+2,31),(x+2,27),(x+3,25)],mid)
                    a.rect(x+1,32,11,2,12);a.line(x+4,height+3,x+4,24,light)
                    if index==0:
                        for y in [16,20]:a.rect(x+3,y,5,2,23)
                    elif index==1:a.rect(x+2,25,8,4,5);a.rect(x+2,11,7,3,3)
                    else:a.poly([(x+5,22),(x+1,15),(x,22),(x+3,26)],41);a.line(x+1,20,x+4,24,42)
            sprites['armor_'+name]=a
    for index in range(6,12):
        a=Art(32,40);colors=[(34,35,36),(31,32,33),(3,4,5),(26,27,28),(12,13,14),(37,40,41)][index-6]
        a.poly([(8,17),(12,13),(21,13),(26,18),(26,29),(21,34),(11,34),(6,29),(6,21)],1)
        a.poly([(9,18),(13,15),(20,15),(24,19),(24,28),(20,32),(12,32),(8,28),(8,21)],23)
        a.poly([(12,21),(20,21),(21,27),(18,29),(13,29),(11,27)],1)
        r=3+index%3
        a.poly([(16,4),(16+r+2,11),(16+r,18),(16-r,18),(14-r,11)],colors[0])
        a.poly([(16,6),(16+r,11),(16,16),(16-r+1,11)],colors[1]);a.rect(15,8,2,3,colors[2])
        if index%2:a.poly([(9,12),(5,8),(6,16),(11,19)],colors[2]);a.poly([(23,12),(27,8),(26,16),(21,19)],colors[2])
        a.dots([(9,20),(23,20),(12,31)],25)
        sprites['ring_'+str(index)]=a
    a=Art(32,40)
    a.poly([(6,17),(11,12),(22,12),(27,17),(27,29),(22,35),(10,35),(5,29)],1)
    a.poly([(8,18),(12,14),(21,14),(25,18),(25,28),(21,33),(11,33),(7,28)],32)
    a.poly([(11,21),(21,21),(21,28),(18,30),(13,30),(10,27)],1)
    a.poly([(16,2),(23,9),(22,18),(16,22),(10,18),(9,9)],31)
    a.poly([(16,5),(20,10),(19,16),(16,19),(13,16),(12,10)],40)
    a.line(16,7,16,16,42);a.rect(12,11,9,2,41);a.dots([(7,17),(24,17),(11,32),(21,32)],25)
    sprites['ring_abyss_seal']=a
    for index,name in enumerate(['healing','training','gold','duration','unyielding']):
        a=Art(32,40);color=[35,28,24,41,33][index]
        for x,y in [(5,5),(7,11),(10,17),(16,20),(22,17),(25,11),(27,5)]:a.rect(x-1,y-1,3,3,23);a.rect(x,y,1,1,25)
        if index==0:
            a.rect(12,22,8,13,1);a.rect(9,25,14,7,1);a.rect(13,23,6,11,color);a.rect(10,26,12,5,color)
        elif index==1:
            a.poly([(8,24),(15,22),(16,25),(18,22),(25,24),(25,35),(18,33),(16,36),(14,33),(8,35)],1)
            a.rect(10,25,5,7,color);a.rect(18,25,5,7,29);a.line(16,26,16,34,23)
        elif index==2:
            a.poly([(16,21),(24,25),(24,33),(16,38),(8,33),(8,25)],1);a.poly([(16,23),(22,26),(22,32),(16,35),(10,32),(10,26)],color)
            a.line(16,25,16,33,25);a.rect(13,27,7,1,15);a.rect(13,30,7,1,15)
        elif index==3:
            a.rect(10,21,13,3,23);a.rect(10,35,13,3,23)
            a.poly([(12,24),(21,24),(19,29),(21,35),(12,35),(14,29)],1)
            a.poly([(13,25),(20,25),(16,29)],color);a.poly([(16,31),(20,34),(13,34)],color)
        else:
            a.poly([(16,21),(25,25),(23,34),(16,39),(9,34),(7,25)],1)
            a.poly([(16,23),(23,26),(21,33),(16,36),(11,33),(9,26)],color)
            a.poly([(16,25),(19,30),(16,34),(13,30)],42)
        sprites['necklace_'+name]=a
    for scope in ['permanent','floor','timed']:
        for index,stat in enumerate(['hp','attack','defense','agility','crit','crit_damage','luck']):
            a=Art(32,40);dark,mid,light=[(34,35,36),(46,47,48),(37,38,39),(26,27,28),(31,32,33),(15,23,25),(7,9,11)][index]
            if scope=='permanent':
                a.poly([(15,10),(10,9),(5,14),(4,25),(9,32),(16,35),(23,32),(28,25),(27,14),(22,9)],1)
                a.poly([(15,12),(10,11),(7,15),(6,24),(10,30),(16,33),(22,30),(26,24),(25,15),(21,11)],mid)
                a.line(16,6,16,13,13);a.poly([(17,8),(20,3),(27,4),(23,9)],28);a.rect(9,15,3,6,light)
            elif scope=='floor':
                a.rect(11,3,10,5,13);a.rect(12,3,8,2,17)
                a.poly([(10,8),(22,8),(22,17),(27,23),(26,34),(6,34),(5,23),(10,17)],1)
                a.poly([(12,9),(20,9),(20,18),(25,24),(24,32),(8,32),(7,24),(12,18)],38)
                a.poly([(9,23),(23,23),(24,31),(8,31)],mid);a.line(10,11,10,17,42)
                a.rect(10,18,12,3,23)
            else:
                a.rect(12,2,8,6,13);a.rect(13,2,6,2,17)
                a.poly([(11,8),(21,8),(21,18),(27,25),(25,34),(20,38),(12,38),(7,34),(5,25),(11,18)],1)
                a.poly([(13,9),(19,9),(19,19),(25,25),(23,33),(19,36),(13,36),(9,33),(7,25),(13,19)],40)
                a.poly([(9,25),(23,25),(22,32),(18,35),(14,35),(10,32)],mid);a.line(10,23,9,28,42)
                a.rect(11,12,10,2,23)
            # Stat glyphs are geometric, not labels: cross / blade / shield / wing / eye / star / clover.
            if index==0:a.rect(14,20,4,10,light);a.rect(11,23,10,4,light)
            elif index==1:a.line(13,29,20,20,light);a.line(12,26,16,29,light);a.rect(11,29,2,2,dark)
            elif index==2:a.poly([(11,21),(21,21),(20,27),(16,31),(12,27)],light);a.line(16,22,16,28,dark)
            elif index==3:
                for k in range(3):a.line(12,23+k*3,21-k*2,20+k*3,light)
            elif index==4:a.poly([(10,25),(16,21),(22,25),(16,29)],light);a.rect(15,23,3,4,dark)
            elif index==5:a.poly([(16,20),(18,24),(23,25),(19,27),(20,32),(16,29),(12,32),(13,27),(9,25),(14,24)],light)
            else:
                for x,y in [(12,22),(18,22),(12,27),(18,27)]:a.rect(x,y,4,4,light)
                a.line(16,27,17,33,dark)
            sprites['consumable_'+scope+'_'+stat]=a
